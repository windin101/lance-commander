#!/usr/bin/env python3
"""T5/T6 (brought forward, T3 review 2026-10-25): decal placements and decal textures for the v3 terrain.

    python3 -I tools/art/terrain/terrain_dress.py mc2_01 [mc2_14 ...]

Writes game/assets/terrain/v3/decals/{tracks,oil,grime}.png (procedural, original work, CC0 like the rest of this
repo's generated art) once, and per map game/assets/terrain/v3/<map>/decals.json: [{"t": kind, "x", "y" (sim metres),
"yaw" (deg), "w", "l" (m)}]:
  tracks   tyre/tread tracks on the verges beside roads, along the road (structure-tensor direction of the road cells)
  oil      oil and fuel stains near buildings (class-1 objects)
  grime    ragged dark grime where scree/apron ground meets open ground, broken along the edge
  crater   old craters and scorch (the game's own crater_N.png / scorch.png), sparse, away from roads and buildings
Scatter (rocks, debris, bushes, grass tufts) is placed at run time from the splat (terrain_dress_v3.gd), seeded.
"""
import json
import zlib
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter
from scipy.ndimage import gaussian_filter, zoom, binary_dilation, binary_erosion

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
DST = ROOT / "game/assets/terrain/v3"
IMPORT = """[remap]

importer="texture"
type="CompressedTexture2D"

[params]

compress/mode=2
compress/high_quality=true
mipmaps/generate=true
process/fix_alpha_border=true
detect_3d/compress_to=0
"""


def textures():
    o = DST / "decals"; o.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(7)
    # tracks: two parallel tread bands, 512 x 1024 (u across, v along), dark compressed soil with chevron tread
    W, H = 256, 1024
    a = np.zeros((H, W)); y, x = np.mgrid[0:H, 0:W]
    for cx in (64, 192):
        band = np.exp(-((x - cx) / 26.0) ** 8)
        tread = 0.6 + 0.4 * (np.sin((y + np.abs(x - cx) * 1.2) / 6.0) > 0.2)
        a = np.maximum(a, band * tread)
    a *= gaussian_filter(rng.random((H, W)), 6) * 1.6
    a *= np.clip(1.2 - np.abs(y - H / 2) / (H / 2), 0, 1) ** 0.5     # fade at both ends
    a = gaussian_filter(np.clip(a, 0, 1), 1.0) * 0.75
    rgba = np.dstack([np.full((H, W), 52), np.full((H, W), 44), np.full((H, W), 36), a * 255]).astype(np.uint8)
    Image.fromarray(rgba, "RGBA").save(o / "tracks.png")
    # oil: an irregular dark stain with a darker core, 512 x 512
    S = 512; y, x = np.mgrid[0:S, 0:S] - S / 2
    r = np.hypot(x, y) / (S / 2)
    ang = np.arctan2(y, x)
    edge = 0.62 + 0.18 * gaussian_filter(rng.standard_normal(720), 12)[((ang + np.pi) / (2 * np.pi) * 719).astype(int)] * 6
    m = np.clip((edge - r) * 6, 0, 1) * (0.55 + 0.45 * gaussian_filter(rng.random((S, S)), 9) * 1.8)
    m = gaussian_filter(np.clip(m, 0, 1), 2)
    rgba = np.dstack([np.full((S, S), 18), np.full((S, S), 17), np.full((S, S), 16), np.clip(m * 0.85, 0, 1) * 255]).astype(np.uint8)
    Image.fromarray(rgba, "RGBA").save(o / "oil.png")
    # grime: ragged, broken dark-earth band along one long edge (v across the edge), 1024 x 256
    W, H = 1024, 256; y, x = np.mgrid[0:H, 0:W]
    n = sum(gaussian_filter(rng.standard_normal((H, W)), s) * s for s in (3, 9, 24)); n = (n - n.mean()) / n.std()
    prof = np.clip(1.0 - y / (H * 0.8), 0, 1) ** 1.5
    m = np.clip(prof * 1.3 + 0.35 * n - 0.4, 0, 1) * np.clip(np.minimum(x, W - x) / 120.0, 0, 1)
    rgba = np.dstack([np.full((H, W), 48), np.full((H, W), 42), np.full((H, W), 34), gaussian_filter(m, 1.2) * 200]).astype(np.uint8)
    Image.fromarray(rgba, "RGBA").save(o / "grime.png")
    for f in ("tracks", "oil", "grime"):
        (o / f"{f}.png.import").write_text(IMPORT)
    (o / "SOURCE.txt").write_text("tracks.png, oil.png, grime.png: procedural, generated by tools/art/terrain/terrain_dress.py "
                                  "(seed 7); original work of this project. Craters and scorch reuse res://assets/decals/.\n")


def run(m):
    t = json.loads((ROOT / f"game/data/maps/{m}/terrain.json").read_text())
    V, wupv, mpu = t["vertices_per_side"], t["world_units_per_vertex"], t["meters_per_world_unit"]
    side = V * wupv * mpu; half = side / 2
    cb = t["cell_bits"]
    cells = np.fromfile(ROOT / f"game/data/maps/{m}/cells.bin", dtype="<u4"); nc = int(round(np.sqrt(cells.size))); cells = cells.reshape(nc, nc)
    bit = lambda k: ((cells >> cb[k][0]) & cb[k][1]) > 0
    road, deep, forest = bit("road"), bit("deep"), bit("forest")
    cm = side / nc
    rng = np.random.default_rng(zlib.crc32(m.encode()))  # str hash() is salted per process
    out = []
    to_sim = lambda r, c: (-half + (c + 0.5) * cm, half - (r + 0.5) * cm)
    # tracks: beside the road, along it
    if road.any():
        rf = gaussian_filter(road.astype(float), 1.0)
        gy, gx = np.gradient(rf)
        jxx, jyy, jxy = gaussian_filter(gx * gx, 2), gaussian_filter(gy * gy, 2), gaussian_filter(gx * gy, 2)
        ang = 0.5 * np.arctan2(2 * jxy, jxx - jyy)          # across-road direction (cells: x right, y down)
        verge = binary_dilation(road, iterations=1) & ~road & ~deep
        rr, cc = np.nonzero(verge)
        keep = rng.random(len(rr)) < 0.06
        for r, c in zip(rr[keep], cc[keep]):
            x, y = to_sim(r, c)
            a = ang[r, c]   # across in cell frame; along = a + 90 deg; sim y is up so flip sign
            along = np.degrees(-(a + np.pi / 2))
            out.append({"t": "tracks", "x": round(x + rng.normal(0, 1.5), 1), "y": round(y + rng.normal(0, 1.5), 1),
                        "yaw": round(float(along + rng.normal(0, 6)), 1), "w": 3.2, "l": round(float(rng.uniform(9, 16)), 1)})
    # oil near buildings
    o = json.loads((ROOT / f"game/data/maps/{m}/objects.json").read_text())
    bld = []
    for ob in o["objects"]:
        ty = o["types"].get(str(ob["type"]))
        if ty and ty.get("class") == 1:
            bld.append((ob["x"] * mpu, ob["y"] * mpu, ty.get("extent_radius", 30.0)))
    for (x, y, er) in bld:
        er_m = er * mpu
        for _ in range(int(rng.random() < 0.35)):
            a = rng.uniform(0, 2 * np.pi); d = er_m * rng.uniform(1.1, 2.2)
            out.append({"t": "oil", "x": round(x * 1.0 + np.cos(a) * d, 1), "y": round(y * 1.0 + np.sin(a) * d, 1),
                        "yaw": round(float(rng.uniform(0, 360)), 1), "w": round(float(rng.uniform(2.5, 6)), 1), "l": 0})
    # grime along apron / scree edges (from the splat)
    sp = np.asarray(Image.open(DST / m / "splat.png"))[..., 0]
    n = sp.shape[0]; px = side / n
    scree = sp == 4
    edge = binary_dilation(scree, iterations=2) & ~scree
    rr, cc = np.nonzero(edge)
    keep = rng.random(len(rr)) < 0.0035
    sf = gaussian_filter(scree.astype(float), 3); gy, gx = np.gradient(sf)
    for r, c in zip(rr[keep], cc[keep]):
        x, y = -half + (c + 0.5) * px, half - (r + 0.5) * px
        yaw = np.degrees(np.arctan2(-gy[r, c], gx[r, c]))   # the band's dark side faces the apron
        out.append({"t": "grime", "x": round(x, 1), "y": round(y, 1), "yaw": round(float(yaw + 90), 1),
                    "w": round(float(rng.uniform(10, 20)), 1), "l": round(float(rng.uniform(3, 6)), 1)})
    # old craters and scorch, sparse, on open ground
    open_ = (sp <= 1) | (sp == 5)
    for _ in range(int(side / 2560 * 60)):
        r, c = rng.integers(0, n, 2)
        if not open_[r, c]:
            continue
        x, y = -half + (c + 0.5) * px, half - (r + 0.5) * px
        out.append({"t": "crater" if rng.random() < 0.6 else "scorch", "x": round(x, 1), "y": round(y, 1),
                    "yaw": round(float(rng.uniform(0, 360)), 1), "w": round(float(rng.uniform(4, 11)), 1), "l": 0,
                    "v": int(rng.integers(0, 4))})
    (DST / m / "decals.json").write_text(json.dumps(out))
    kinds = {k: sum(1 for d in out if d["t"] == k) for k in ("tracks", "oil", "grime", "crater", "scorch")}
    print(m, kinds)


if __name__ == "__main__":
    textures()
    for m in sys.argv[1:]:
        run(m)
