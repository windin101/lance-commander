#!/usr/bin/env python3
"""v3 building material library (LANCE-21): ambientCG CC0 1K sets packed for res://shaders/building_v3.gdshader.

    python3 -I tools/art/v3/bld_materials.py            # downloads missing sets to $BLD_CACHE, writes game/assets/v3/shared/buildings/

Per material two WebP files (lossy RGB q92, lossless alpha), the packing the terrain arrays use:
  <name>_ar.webp   albedo RGB, roughness A            (sampled sRGB, A is data)
  <name>_nm.webp   OpenGL normal R,G ; metalness B ; ambient occlusion A (z is rebuilt in the shader)
plus materials.json (source id, URL, tile size in metres, mean albedo) and LICENSE.md. The shader reads UV as metres
and divides by tile_m, so a mesh never needs per-material UV scale.
"""
import io
import json
import os
import urllib.request
import zipfile
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
DST = ROOT / "game/assets/v3/shared/buildings"
CACHE = Path(os.environ.get("BLD_CACHE", "/mnt/nvme1n1p1/mc2-rework/bld/amb"))
UA = {"User-Agent": "Mozilla/5.0"}

# name: (ambientCG id, tile metres, what it is used for)
LIB = {
    "paint": ("PaintedMetal012", 2.0, "white painted steel with chipped paint: tank shells, housings"),
    "steel": ("Metal046A", 1.5, "dark rolled steel: railings, ladders, pipes, flanges"),
    "galv": ("Metal032", 1.5, "galvanised sheet: roofs, hatches, gutters"),
    "concrete": ("Concrete034", 2.0, "light poured concrete: plinths, bunds, pads"),
    "concrete_dark": ("Concrete042A", 2.0, "dark weathered concrete: aprons, retaining walls"),
    "grate": ("DiamondPlate008C", 0.8, "diamond tread plate: walkways, stair treads"),
    "rust": ("Rust009", 1.5, "corroded steel: wrecks, exposed interiors"),
    "corrugated": ("CorrugatedSteel009", 1.0, "corrugated cladding: sheds, silos, hoods"),
    "wood": ("Planks023A", 2.0, "weathered grey-brown planks: hut cladding, timber frames, decks"),
    "boards": ("Planks008", 1.5, "vertical boards: board-and-batten walls, fences"),
}


def fetch(i):
    d = CACHE / i
    if not d.is_dir():
        z = urllib.request.urlopen(urllib.request.Request(f"https://ambientcg.com/get?file={i}_1K-JPG.zip", headers=UA), timeout=120).read()
        d.mkdir(parents=True)
        zipfile.ZipFile(io.BytesIO(z)).extractall(d)
    return d


def find(d, key):
    return next((d / f for f in sorted(os.listdir(d)) if key in f and f.endswith((".jpg", ".png"))), None)


def save(arr, path, q=92):
    Image.fromarray(arr).save(path, "WEBP", quality=q, alpha_quality=100, method=6)


def main():
    DST.mkdir(parents=True, exist_ok=True)
    info = {}
    for name, (i, tile, use) in LIB.items():
        d = fetch(i)
        col = np.asarray(Image.open(find(d, "_Color")).convert("RGB").resize((1024, 1024), Image.LANCZOS))
        rp, npth, mp, ap = find(d, "_Roughness"), find(d, "_NormalGL"), find(d, "_Metalness"), find(d, "_AmbientOcclusion")
        r = np.asarray(Image.open(rp).convert("L").resize((1024, 1024))) if rp else np.full((1024, 1024), 200, np.uint8)
        n = np.asarray(Image.open(npth).convert("RGB").resize((1024, 1024))) if npth else np.full((1024, 1024, 3), (128, 128, 255), np.uint8)
        m = np.asarray(Image.open(mp).convert("L").resize((1024, 1024))) if mp else np.zeros((1024, 1024), np.uint8)
        ao = np.asarray(Image.open(ap).convert("L").resize((1024, 1024))) if ap else np.full((1024, 1024), 255, np.uint8)
        save(np.dstack([col, r]), DST / f"{name}_ar.webp")
        save(np.dstack([n[..., 0], n[..., 1], m, ao]), DST / f"{name}_nm.webp")
        info[name] = {"source": f"{i} by ambientCG.com (CC0 1.0), https://ambientcg.com/view?id={i}", "tile_m": tile,
                      "use": use, "mean_albedo": col.reshape(-1, 3).mean(0).round(1).tolist(),
                      "mean_roughness": round(float(r.mean()), 1), "metal": round(float(m.mean()), 1)}
        print(name, i)
    (DST / "materials.json").write_text(json.dumps(info, indent=1) + "\n")
    lines = ["# Building material library (v3)\n",
             "Packed by `tools/art/v3/bld_materials.py` from ambientCG 1K-JPG sets. ambientCG assets are CC0 1.0 (public domain),",
             "https://docs.ambientcg.com/license/ . No attribution is required; it is given here anyway.\n"]
    lines += [f"- `{k}_ar.webp`, `{k}_nm.webp`: {v['source']}" for k, v in info.items()]
    lines += ["", "`trim_*.png` and `decals_*.png` are generated by `tools/art/v3/bld_trim.py` (project-made, no outside source;",
              "stencil numerals are set in Oswald, SIL OFL 1.1, from race-into-space/game/assets/fonts)."]
    (DST / "LICENSE.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
