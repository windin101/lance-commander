#!/usr/bin/env python3
"""Plan HD redos deterministically from the seed history, so nobody guesses a seed.

    python3 -I tools/art/hd_redo.py [--approved a,b,c] [--apply] [--script original/hd/logs/swarm_bN.sh]

For every mech with an open "HD <mech>: <verdict>" issue in swarm/state.json:
- keeps exactly one open redo issue per mech (the newest) and closes the older ones as duplicates;
- closes every open redo issue of a mech listed in --approved (the review just approved it);
- writes the repro from the history in original/hd/<mech>/:
    reseed_concept -> next untried concept seed (concept_seeds_tried, concept_rejected_s*, concept_s*);
                      from step 1 with --subject-px 560 when the issue says the concept is cropped
    reseed_mesh    -> next mesh seed not in mesh_seeds_tried (every mech was first meshed on 1234)
    turn           -> --from-step 4 --turn
  and adds --prompt vehicles for the copters.
Without --apply it only prints the plan. --script writes the batch script (one line per redo).
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HD = ROOT / "original" / "hd"
SWARM = Path.home() / "Code" / "remake-kit" / "bin" / "swarm"
MESH_SEEDS = [1234, 4242, 777, 2024, 9001, 31337, 8080, 555]
VEHICLE_PROMPT = {"mediumcopter", "heavycopter"}
VERDICTS = ("turn", "reseed_concept", "reseed_mesh")


def history(m):
    w = HD / m
    p = json.loads((w / "provenance.json").read_text()) if (w / "provenance.json").exists() else {}
    concept = set(p.get("concept_seeds_tried", []))
    if p.get("concept_seed") is not None:
        concept.add(int(p["concept_seed"]))
    for f in w.glob("concept*_s*.png"):
        if (n := re.search(r"_s(\d+)\.png$", f.name)):
            concept.add(int(n[1]))
    mesh = set(p.get("mesh_seeds_tried", [])) | {1234}
    if p.get("mesh_seed") is not None:
        mesh.add(int(p["mesh_seed"]))
    return p, concept, mesh


def plan(m, verdict, detail):
    p, concept, mesh = history(m)
    extra = " --prompt vehicles" if m in VEHICLE_PROMPT else ""
    if verdict == "turn":
        return f"python3 -I tools/art/hd_mech.py {m} --from-step 4 --turn", "turn the existing fit"
    if verdict == "reseed_mesh":
        seed = next(s for s in MESH_SEEDS if s not in mesh)
        return (f"python3 -I tools/art/hd_mech.py {m} --from-step 3 --mesh-seed {seed}{extra}",
                f"mesh seeds tried {sorted(mesh)} -> {seed}")
    seed = max(concept | {7}) + 1
    crop = "crop" in (detail or "").lower()
    step = f"--from-step 1 --subject-px 560" if crop else "--from-step 2"
    return (f"python3 -I tools/art/hd_mech.py {m} {step} --seed {seed}{extra}",
            f"concept seeds tried {sorted(concept)} -> {seed}" + ("; cropped, re-render with more margin" if crop else ""))


def swarm(*a):
    subprocess.run([str(SWARM), "--repo", str(ROOT), *a], check=True, capture_output=True, text=True)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--approved", default="")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--script")
    a = ap.parse_args()
    approved = {x.strip() for x in a.approved.split(",") if x.strip()}
    st = json.loads((ROOT / "swarm" / "state.json").read_text())
    by = {}
    for i in st["issues"]:
        t = i["title"]
        if i["status"] == "open" and t.startswith("HD ") and ":" in t and t.split(":", 1)[1].strip() in VERDICTS:
            by.setdefault(t[3:].split(":")[0].strip().lower(), []).append(i)
    lines = []
    for m, issues in sorted(by.items()):
        issues.sort(key=lambda i: int(i["id"][1:]))
        if m in approved:
            for i in issues:
                print(f"close {i['id']} {m}: approved")
                a.apply and swarm("issue", "close", i["id"], "--note", f"{m} approved in review")
            continue
        keep, older = issues[-1], issues[:-1]
        for i in older:
            print(f"close {i['id']} {m}: superseded by {keep['id']}")
            a.apply and swarm("issue", "close", i["id"], "--status", "duplicate", "--note", f"superseded by {keep['id']}")
        verdict = keep["title"].split(":", 1)[1].strip()
        repro, why = plan(m, verdict, keep.get("detail"))
        print(f"keep  {keep['id']} {m} {verdict}: {repro}   ({why})")
        if a.apply and repro != keep.get("repro"):
            swarm("issue", "update", keep["id"], "--repro", repro, "--note", f"repro planned by hd_redo.py: {why}")
        lines.append((keep["id"], m, repro))
    if a.script:
        out = ["#!/usr/bin/env bash", "# Generated by tools/art/hd_redo.py from the open HD redo issues.",
               'cd "$(dirname "$0")/../../.."', "export COMFY_SERVER=http://127.0.0.1:8188", f"L={Path(a.script).parent}"]
        log = f"$L/{Path(a.script).stem}.log"
        for iid, m, repro in lines:
            out.append(f'echo "== {iid} {m} $(date +%H:%M)" >> {log}; {repro} >> {log} 2>&1 && echo "OK {iid} {m}" >> {log} || echo "FAIL {iid} {m}" >> {log}')
        out.append(f"echo {Path(a.script).stem.upper()}_DONE >> {log}")
        Path(a.script).write_text("\n".join(out) + "\n")
        Path(a.script).chmod(0o755)
        print(f"wrote {a.script} ({len(lines)} redos)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
