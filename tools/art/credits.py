LIC_NAME = {"CC BY 4.0": "Attribution 4.0 International", "CC BY-SA 4.0": "Attribution-ShareAlike 4.0 International",
            "CC BY-NC 4.0": "Attribution-NonCommercial 4.0 International", "CC BY-NC-SA 4.0": "Attribution-NonCommercial-ShareAlike 4.0 International"}
CHANGES = {
    "mech": ("scaled from the miniature to game size and centred, feet on the ground; display base removed where it had one; "
             "cut into rigid parts at the hips, knees, ankles and upper body; legs re-posed from the sculpted pose to the "
             "MechCommander 2 rest pose (MC2 bone directions, the sculpt's bone lengths); seams smoothed and dark joint caps "
             "added at the leg cuts; painted by region (team-colour mask); bound to the MC2 skeleton so the game's animations move it"),
    "rigid": ("loose kit pieces (turret, guns, launchers, rotor) put in place on the hull and display bases, sprues and spare "
              "pieces removed; the mesh simplified (vertex clustering); scaled, turned and fitted to the MechCommander 2 model it "
              "replaces; each part bound to the game model's moving parts (turret, launcher, rotor); painted by region from the "
              "original model's team-colour mask"),
    "static": ("display bases, sprues and spare pieces removed; the mesh simplified (vertex clustering); scaled, turned and "
               "fitted to the footprint and height of the MechCommander 2 map object it replaces, standing on the ground; "
               "painted by region from the original model's own colours"),
}
# Sources whose uploader says they are remixes or assemblies of other models whose licences could not be confirmed.
# Lee approved their use on 2026-10-19; the notice says so plainly.
UNVERIFIED = {
    "thing:6459522": "The uploader says this model was assembled from two other models (a missile battery pack and a 6 mm Hetzer by wolverine_dh, both on Cults3D) whose licences are not stated.",
    "model/108618": "The uploader says the files in this set are remixes of originals they could not trace.",
    "model/108619": "The uploader says the files in this set are remixes of originals they could not trace.",
    "model/108620": "The uploader says the files in this set are remixes of originals they could not trace.",
    "model/108632": "The uploader says this model is built on a remixed truck whose original they could not trace.",
    "thing:7089967": "The uploader says this is a kitbash based on a ZEU-5T by Matt Mason, with a left arm from OSWALDODDITIES' American Mecha model on Cults3D; the licences of those parts are not stated.",
}
BEGIN, END = "<!-- adapted-models:begin (generated by tools/art/credits.py) -->", "<!-- adapted-models:end -->"


def adapted():
    out = []
    for p in sorted((ROOT / "original/hd").glob("*/provenance.json")):
        d = json.loads(p.read_text())
        folder = d.get("class") if d.get("class") in ("vehicles", "objects") else "mechs"
        if d.get("kind") == "adapted" and (ROOT / f"game/assets/{folder}/{d['asset']}_hd.glb").exists():
            d["_folder"] = folder
            out.append(d)
    return out


def parse(src):
    """'"Title" by Author, URL [and URL]' or "Author, 'Title' (printables.com/...)" -> (titles text, author, [urls])."""
    urls = [u.rstrip(").,") for u in re.findall(r"(?:https?://)?(?:www\.)?(?:printables\.com|thingiverse\.com)/[^\s,)]+", src)]
    urls = [u if u.startswith("http") else "https://www." + u.removeprefix("www.") for u in urls]
    if " by " in src:
        titles, rest = src.rsplit(" by ", 1)
        author = rest.split(",")[0].strip()
        titles = titles.strip()
    else:
        author = src.split(",")[0].strip()
        titles = "'".join(src.split("'")[1:-1]) or src
        titles = f'"{titles}"'
    if not titles.startswith('"'):
        titles = f'"{titles}"'
    return titles, author, urls


def name(asset):
    return {"jaegermech": "JagerMech", "madcat": "MadCat", "urbanmech": "UrbanMech", "mediumcopter": "Attack copter",
            "heavycopter": "Heavy copter", "laohu": "Lao Hu", "shayu": "Sha Yu", "menshen": "Men Shen", "mobilehq": "Mobile HQ",
            "lrmc": "LRM carrier", "swarmlrmc": "Swarm LRM carrier", "apc": "APC", "mog": "MOG", "armoredcar": "Armoured car",
            "cargotruck": "Cargo truck", "fueltruck": "Fuel truck", "ordnancetruck": "Ordnance truck", "repairtruck": "Repair truck",
            "trooptransport": "Troop transport", "aerospotter": "AeroSpotter", "slayerp": "Parked Slayer",
            "shilonep": "Parked Shilone", "privatejet": "Private jet", "dropshipdavion": "Dropship (tan)",
            "dropshipsteiner": "Dropship (blue)", "dropshipliao": "Dropship (green)", "lifeboat": "Lifeboat"}.get(asset, asset.capitalize())


def notice(d):
    titles, author, urls = parse(d.get("source", ""))
    lic = d.get("licence") or "CC BY-NC-SA 4.0"
    tool = d.get("tool", "tools/art/stl_rig.py")
    rigid = tool.endswith("stl_hd.py")
    a, f = d["asset"], d["_folder"]
    unv = [v for k, v in UNVERIFIED.items() if any(k in u for u in urls)]
    static = f == "objects"
    skel = ("The skeleton, joint names and animations in the same `.glb` are converted from Microsoft's 2006 MechCommander 2 "
            "Shared Source release" if not rigid else
            "The node names and placement in the same `.glb` are converted from Microsoft's 2006 MechCommander 2 Shared Source release" if static else
            "The part hierarchy, pivots and animations in the same `.glb` are converted from Microsoft's 2006 MechCommander 2 Shared Source release")
    return f"""# {a}_hd.glb — licence and attribution

The 3D mesh of the HD {name(a)} in `{a}_hd.glb` (and its paint mask `{a}_hd_paint.bin`) is an adaptation of:

> **{titles}** by **{author}**, {' and '.join(urls)}
> licensed under **Creative Commons {LIC_NAME.get(lic, lic)} ({lic})**, {LIC_URL.get(lic, '')}
{chr(10) + "**Rights note.** " + " ".join(unv) + " Lee Osborne approved its use on 2026-10-19 on the strength of the licence shown on the page. If you hold rights in the original material and want it removed, please open an issue." + chr(10) if unv else ""}
## Changes made

The original STL was modified for use as a game model: {CHANGES['static' if static else 'rigid' if rigid else 'mech']}{('; ' + d['extra_changes']) if d.get('extra_changes') else ''}. The changes are made by `{tool}`
in this repository (the settings it used: see `original/hd/{a}/provenance.json` in the build tree).

## Licence of this adaptation

This adaptation of the mesh is licensed under **{lic}** ({LIC_URL.get(lic, '')}), the licence of the original. Nothing in this
project restricts what that licence permits for this mesh. {skel} and remain under that release's licence
(`docs/MC2-SOURCE-EULA.md`); they are not covered by the Creative Commons licence.

This is an unofficial fan project. {author} has not endorsed it or this use of their model. The model is provided
as is, without warranties of any kind.
"""


def block(rows, fmt):
    return BEGIN + "\n" + "\n".join(fmt(r) for r in rows) + "\n" + END


def replace_block(text, new, anchor):
    if BEGIN in text:
        a, b = text.index(BEGIN), text.index(END) + len(END)
        return text[:a] + new + text[b:]
    return text.replace(anchor, new + "\n\n" + anchor, 1)


def main():
    check = "--check" in sys.argv
    rows, changed = [], []
    for d in adapted():
        titles, author, urls = parse(d.get("source", ""))
        lic = d.get("licence") or "CC BY-NC-SA 4.0"
        rows.append({"a": d["asset"], "f": d["_folder"], "t": titles, "au": author, "u": " and ".join(urls), "l": lic})
        if d.get("tool", "").endswith("stl_rig_vulture.py"):
            continue  # the Vulture's notice is hand-written with its exact measurements
        p = ROOT / f"game/assets/{d['_folder']}/{d['asset']}_hd.LICENSE.md"
        t = notice(d)
        if not p.exists() or p.read_text() != t:
            changed.append(str(p.relative_to(ROOT)))
            if not check:
                p.write_text(t)
    rows.sort(key=lambda r: (r["f"], r["a"]))
    cred = ROOT / "CREDITS.md"
    c0 = cred.read_text()
    c1 = replace_block(c0, block(rows, lambda r: f"- **{name(r['a'])}** (`game/assets/{r['f']}/{r['a']}_hd.glb`): adapted from {r['t']} by "
                                 f"{r['au']} ({r['u']}), {r['l']} ({LIC_URL.get(r['l'], '')}); changes in `game/assets/{r['f']}/{r['a']}_hd.LICENSE.md`; "
                                 f"the adapted mesh is {r['l']}; not endorsed by {r['au']}."), "### MechCommander 2 Shared Source release")
    readme = ROOT / "README.md"
    r0 = readme.read_text()
    r1 = replace_block(r0, block(rows, lambda r: f"- {name(r['a'])}: {r['t']} by {r['au']}, {r['u']} ({r['l']})"), "## Layout")
    for path, old, new in ((cred, c0, c1), (readme, r0, r1)):
        if old != new:
            changed.append(str(path.relative_to(ROOT)))
            if not check:
                path.write_text(new)
    print(("would change: " if check else "updated: ") + (", ".join(changed) or "nothing") + f" ({len(rows)} adapted models)")
    return 1 if check and changed else 0


if __name__ == "__main__":
    sys.exit(main())
